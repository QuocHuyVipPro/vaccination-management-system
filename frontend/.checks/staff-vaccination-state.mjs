import assert from 'node:assert/strict';
import { availableBatches, completeVaccination, initialVaccinationState, validateVaccination } from '../src/pages/staff/vaccinationState.js';
const initial = structuredClone(initialVaccinationState);
const draft = { appointmentId: 'LH20261008001', batchId: 1, vaccinationDate: '2026-10-08', reaction: 'Không ghi nhận', note: 'Demo', hasNextDose: true, nextDoseDate: '2026-12-08' };
assert.deepEqual(availableBatches(initial.batches,'HPV Gardasil 9','2026-10-08','2026-10-04').map(b=>b.id),[1,2]);
assert.deepEqual(availableBatches(initial.batches,'HPV Gardasil 9','2028-01-01','2026-10-04'),[]);
assert.deepEqual(availableBatches(initial.batches,'HPV Gardasil 9','2020-01-01','2028-01-01'),[]);
for(const batchId of [3,6,7,8,999]) assert.ok(validateVaccination(initial,{...draft,batchId}).batch);
assert.ok(validateVaccination(initial,{...draft,vaccinationDate:''}).date);
assert.ok(validateVaccination(initial,{...draft,nextDoseDate:''}).nextDate);
assert.ok(validateVaccination(initial,{...draft,nextDoseDate:'2026-10-07'}).nextDate);
assert.ok(validateVaccination(initial,{...draft,appointmentId:'LH20261004003'}).appointment);
const completed = completeVaccination(initial,draft);
assert.equal(completed.records.length,1);
assert.equal(completed.batches.find(b=>b.id===1).remainingQuantity,24);
assert.equal(completed.appointments.find(a=>a.id===draft.appointmentId).status,'completed');
assert.equal(initial.batches.find(b=>b.id===1).remainingQuantity,25);
assert.equal(completed.records[0].nextDoseDate,'2026-12-08');
assert.equal(completeVaccination(completed,draft),completed);
assert.equal(completeVaccination(initial,{...draft,batchId:7}),initial);
assert.equal(completeVaccination(initial,{...draft,hasNextDose:false}).records[0].nextDoseDate,null);
console.log('PASS: batch eligibility/expiry/date validation, immutable completion, stock -1, record/next date, invalid and duplicate submission guards.');
