import assert from 'node:assert/strict';
import { initialInventory, batchStatus, applyInventory, validateInventory } from '../src/pages/admin/inventoryState.js';
import { initialVaccines } from '../src/pages/admin/adminVaccineData.js';
const today='2026-10-05';
assert.equal(batchStatus({remainingQuantity:0,expiryDate:'2020-01-01'},today),'empty');
assert.equal(batchStatus({remainingQuantity:1,expiryDate:'2026-10-04'},today),'expired');
assert.equal(batchStatus({remainingQuantity:1,expiryDate:'2026-10-05'},today),'expiring');
assert.equal(batchStatus({remainingQuantity:1,expiryDate:'2026-11-04'},today),'expiring');
assert.equal(batchStatus({remainingQuantity:1,expiryDate:'2026-11-05'},today),'active');
const form={vaccineId:'1',batchNumber:'TEST',manufactureDate:'2026-01-01',expiryDate:'2027-01-01',importedQuantity:'20',purchasePrice:'0',importDate:today};
assert.deepEqual(validateInventory(initialInventory,'import',form,initialVaccines),{});
let state=applyInventory(initialInventory,'import',form,initialVaccines,null,'2026-10-05T12:00:00+07:00');
assert.equal(state.batches.at(-1).remainingQuantity,20);assert.equal(state.transactions.at(-1).quantity,20);
assert.equal(state.transactions.at(-1).batchId,state.batches.at(-1).id);
assert.equal(applyInventory(state,'import',form,initialVaccines,null,today),state);
const batchId=state.batches.at(-1).id;
state=applyInventory(state,'adjust',{quantity:'23',reason:'Kiểm kê',note:''},initialVaccines,batchId,today);
assert.equal(state.transactions.at(-1).quantity,3);assert.equal(state.batches.at(-1).remainingQuantity,23);
state=applyInventory(state,'adjust',{quantity:'21',reason:'Kiểm kê',note:''},initialVaccines,batchId,today);
assert.equal(state.transactions.at(-1).quantity,-2);
assert.ok(validateInventory(state,'discard',{quantity:'22',reason:'Hỏng'},initialVaccines,batchId).quantity);
assert.ok(validateInventory(state,'adjust',{quantity:'-1',reason:'Hỏng'},initialVaccines,batchId).quantity);
assert.ok(validateInventory(state,'adjust',{quantity:'1.5',reason:'Hỏng'},initialVaccines,batchId).quantity);
assert.ok(validateInventory(state,'import',{...form,batchNumber:'new',purchasePrice:''},initialVaccines).purchasePrice);
assert.ok(validateInventory(state,'import',{...form,batchNumber:'new',expiryDate:'2025-01-01'},initialVaccines).expiryDate);
state=applyInventory(state,'discard',{quantity:'21',reason:'Hỏng'},initialVaccines,batchId,today);
assert.equal(state.batches.at(-1).remainingQuantity,0);assert.equal(state.transactions.at(-1).quantity,-21);
assert.equal(state.batches.at(-1).importedQuantity,20);assert.equal(initialInventory.batches.length,8);
console.log('PASS: status boundary dates, immutable atomic import/adjust/discard, signed deltas, preserved batch IDs/original quantities, duplicate and invalid input guards.');
